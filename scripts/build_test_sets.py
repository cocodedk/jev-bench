"""Create or update website/test-sets.html from the decision datasets, so the published test sets match the repo."""

import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from jev_bench.config import loads, validate_dataset

SETS = "datasets/decisions-*.json"
PAGE = "website/test-sets.html"


def section(data: dict) -> str:
    e = html.escape
    criteria = data.get("criteria", {})
    labels = "".join(f"<li><strong>{e(label)}</strong>{' — ' + e(criteria[label]) if label in criteria else ''}</li>"
                     for label in data["labels"])
    rows = "".join(f"<tr><td>{e(case['id'])}</td><td>{e(case['text'])}</td><td>{e(case['expected'])}</td></tr>"
                   for case in data["cases"])
    order = " (ordered, lowest first)" if data.get("type") == "score" else ""
    return f"""
    <section id="{e(data['name'])}" class="results-section" aria-labelledby="{e(data['name'])}-heading">
      <div class="section-heading"><div><p class="eyebrow">{e(data.get('type', 'choice').upper())} · {len(data['cases'])} CASES</p><h2 id="{e(data['name'])}-heading">{e(data['name'])}</h2></div></div>
      <p><strong>Instructions sent with every case:</strong> {e(data['instructions'])}</p>
      <p><strong>Labels{order}:</strong></p><ul>{labels}</ul>
      <div class="table-wrap"><table class="cases"><caption>{e(data['name'])} cases and expected answers</caption><thead><tr><th scope="col">Case</th><th scope="col">Text sent to the model</th><th scope="col">Expected</th></tr></thead><tbody>{rows}</tbody></table></div>
    </section>"""


def build(root: Path = ROOT) -> int:
    sets = [validate_dataset(loads(path.read_bytes())) for path in sorted(root.glob(SETS))]
    if not sets:
        raise ValueError(f"No datasets match {SETS}")
    payload = [{key: data[key] for key in ("name", "type", "instructions", "labels", "criteria", "cases") if key in data}
               for data in sets]
    embedded = json.dumps(payload, ensure_ascii=False).replace("<", "\\u003c")  # no "<" can open or close a tag
    nav = " · ".join(f'<a href="#{html.escape(data["name"])}">{html.escape(data["name"])}</a>' for data in sets)
    page = f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="The Jev Bench decision test sets: every case, its instructions, labels and expected answer.">
  <link rel="canonical" href="https://jev-bench.cocode.dk/test-sets.html">
  <link rel="icon" href="favicon.ico" sizes="16x16 32x32 48x48">
  <link rel="stylesheet" href="styles.css">
  <title>Jev Bench — test sets</title>
</head>
<body>
  <!-- Generated by scripts/build_test_sets.py from {SETS}; edit the datasets, then rerun the script. -->
  <main class="wrap">
    <section class="hero">
      <p class="eyebrow"><a href="./">Jev Bench</a> · TEST SETS</p>
      <h1>The test sets,<br><span>in full.</span></h1>
      <div class="hero-bottom"><p>Every case the decision benchmarks send, with the expected answer the models never see.<br>{nav}</p></div>
    </section>{''.join(section(data) for data in sets)}
  </main>
  <footer class="wrap"><a href="./">Results</a> · <a href="llms.txt">For agents</a></footer>
  <script type="application/json" id="test-sets">{embedded}</script>
  <script type="module" src="test-sets.js"></script>
</body>
</html>
"""
    (root / PAGE).write_text(page, encoding="utf-8")
    return len(sets)


if __name__ == "__main__":
    print(f"Built {PAGE} from {build()} test sets")
